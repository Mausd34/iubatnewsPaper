# Comments (threaded, one level of replies)
# ---------------------------------------------------------------------------
class Comment(models.Model):
    article = models.ForeignKey(
        Article, on_delete=models.CASCADE, related_name="comments"
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="comments",
    )
    body = models.TextField(
        max_length=1000,
        validators=[MinLengthValidator(2)],
    )
    parent = models.ForeignKey(
        "self",
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name="replies",
        help_text="Set when this comment is a reply to another comment.",
    )
    is_approved = models.BooleanField(
        default=True,
        help_text="Unverified users' comments are held for moderation.",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    objects = CommentManager()

    class Meta:
        ordering = ("created_at",)
        verbose_name = "comment"
        verbose_name_plural = "comments"
        indexes = [
            models.Index(fields=["article", "is_approved", "created_at"]),
        ]

    def __str__(self):
        return f"Comment by {self.user.username} on {self.article.title}"

    @property
    def is_reply(self):
        return self.parent_id is not None

    def approve(self):
        self.is_approved = True
        self.save(update_fields=["is_approved", "updated_at"])


# ---------------------------------------------------------------------------
# Reactions (one per user per article; user may change the type)
# ---------------------------------------------------------------------------
class Reaction(models.Model):
    class ReactionType(models.TextChoices):
        LIKE = "like", "👍 Like"
        LOVE = "love", "❤️ Love"
        INSIGHTFUL = "insightful", "💡 Insightful"

    article = models.ForeignKey(
        Article, on_delete=models.CASCADE, related_name="reactions"
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="reactions",
    )
    reaction_type = models.CharField(
        max_length=12, choices=ReactionType.choices, default=ReactionType.LIKE
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ("-created_at",)
        constraints = [
            models.UniqueConstraint(
                fields=["article", "user"],
                name="unique_reaction_per_user_per_article",
            ),
        ]
        verbose_name = "reaction"
        verbose_name_plural = "reactions"

    def __str__(self):
        return f"{self.user.username} {self.reaction_type} → {self.article_id}"


# ---------------------------------------------------------------------------
# Article view log — analytics
# ---------------------------------------------------------------------------
class ArticleView(models.Model):
    article = models.ForeignKey(
        Article, on_delete=models.CASCADE, related_name="article_views"
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="article_views",
    )
    ip = models.GenericIPAddressField(null=True, blank=True)
    user_agent = models.CharField(max_length=400, blank=True)
    referrer = models.URLField(max_length=500, blank=True)
    timestamp = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ("-timestamp",)
        verbose_name = "article view"
        verbose_name_plural = "article views"
        indexes = [
            models.Index(fields=["article", "timestamp"]),
            models.Index(fields=["-timestamp"]),
        ]

    def __str__(self):
        return f"View of {self.article_id} at {self.timestamp:%Y-%m-%d %H:%M}"
